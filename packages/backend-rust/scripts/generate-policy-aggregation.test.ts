import { describe, expect, test } from 'bun:test';
import { readFileSync } from 'node:fs';
import { checkPolicyAggregation, extractPolicyAggregations, generatePolicyAggregation } from './generate-policy-aggregation.js';

const source = readFileSync(new URL('../../backend/src/core/RoleService.ts', import.meta.url), 'utf8');
const descriptor = new URL('../api-auth/src/policy_aggregation.rs', import.meta.url);

function replace(before: string, after: string): string {
	expect(source).toContain(before);
	return source.replace(before, after);
}

describe('Rust policy aggregation generation', () => {
	test('the checked-in typed descriptor matches the authoritative service', () => {
		const generated = generatePolicyAggregation(source);
		expect(() => checkPolicyAggregation(source, readFileSync(descriptor, 'utf8'))).not.toThrow();
		expect(generated).toContain('"rateLimitFactor" => Aggregation::Max,');
		expect(generated).toContain('"maxFileSizeMb" => Aggregation::MaxFileSize,');
		expect(generated).toContain('"chatAvailability" => Aggregation::Chat,');
		expect(generated).toContain('"uploadableFileTypes" => Aggregation::FileTypes,');
	});

	test('a policy added to all authoritative declarations is generated without another name table', () => {
		const updated = source
			.replace('export type RolePolicies = {', 'export type RolePolicies = {\n futureLimit: number;')
			.replace('export const DEFAULT_POLICIES: RolePolicies = {', 'export const DEFAULT_POLICIES: RolePolicies = {\n futureLimit: 3,')
			.replace("gtlAvailable: calc('gtlAvailable',", "futureLimit: calc('futureLimit', vs => Math.max(...vs)),\n gtlAvailable: calc('gtlAvailable',");
		const policies = extractPolicyAggregations(updated);
		expect(policies.length).toBe(extractPolicyAggregations(source).length + 1);
		expect(policies[0]).toEqual({ name: 'futureLimit', aggregation: 'Max' });
		expect(generatePolicyAggregation(updated)).toContain('"futureLimit" => Aggregation::Max,');
		expect(() => checkPolicyAggregation(updated, generatePolicyAggregation(source))).toThrow('stale');
	});

	test('formatting, comments and quote styles leave the descriptor unchanged', () => {
		const updated = replace("gtlAvailable: calc('gtlAvailable', vs => vs.some(v => v === true)),",
			'gtlAvailable: calc("gtlAvailable", vs => vs.some(v => v /* strict true */ === true)),');
		expect(generatePolicyAggregation(updated)).toBe(generatePolicyAggregation(source));
	});

	test('check mode rejects altered generated bytes', () => {
		expect(() => checkPolicyAggregation(source, generatePolicyAggregation(source) + '\n')).toThrow('stale');
	});

	test.each([
		['missing default', '\twatermarkAvailable: true,\n', ''],
		['extra default', 'export const DEFAULT_POLICIES: RolePolicies = {', 'export const DEFAULT_POLICIES: RolePolicies = {\n futurePolicy: true,'],
		['missing type key', '\twatermarkAvailable: boolean;\n', ''],
		['duplicate type key', 'export type RolePolicies = {', 'export type RolePolicies = {\n gtlAvailable: boolean;'],
		['missing returned key', "\t\t\twatermarkAvailable: calc('watermarkAvailable', vs => vs.some(v => v === true)),\n", ''],
		['extra returned key', "gtlAvailable: calc('gtlAvailable',", "futurePolicy: calc('futurePolicy', vs => vs.some(v => v === true)),\n gtlAvailable: calc('gtlAvailable',"],
		['duplicate returned key', "gtlAvailable: calc('gtlAvailable',", "gtlAvailable: calc('gtlAvailable', vs => vs.some(v => v === true)),\n gtlAvailable: calc('gtlAvailable',"],
		['mismatched calc key', "gtlAvailable: calc('gtlAvailable',", "gtlAvailable: calc('canInvite',"],
		['unknown policy type', '\tmentionLimit: number;', '\tmentionLimit: string;'],
		['wrong typed aggregator', "gtlAvailable: calc('gtlAvailable', vs => vs.some(v => v === true))", "gtlAvailable: calc('gtlAvailable', vs => Math.max(...vs))"],
	])('rejects %s', (_name, before, after) => {
		expect(() => generatePolicyAggregation(replace(before, after))).toThrow('Unsupported RoleService policy source');
	});

	test.each([
		['truthiness instead of strict boolean', 'vs => vs.some(v => v === true)', 'vs => vs.some(v => !!v)'],
		['unsupported numeric aggregate', 'vs => Math.max(...vs)', 'vs => Math.min(...vs)'],
		['changed chat precedence', "if (vs.some(v => v === 'available')) return 'available';", "if (vs.some(v => v === 'unavailable')) return 'unavailable';"],
		['changed file-type normalization', "if (type.trim() === '') continue;", "if (type.toLowerCase() === '') continue;"],
		['changed file-size cap', 'Math.floor(this.config.maxFileSize / (1024 * 1024))', 'Math.ceil(this.config.maxFileSize / (1024 * 1024))'],
		['changed cap application', 'Math.min(serverMaxFileSizeMb, Math.max(...vs))', 'Math.max(serverMaxFileSizeMb, Math.max(...vs))'],
		['changed priority selection', 'policy.priority === 2', 'policy.priority === 3'],
		['changed base override precedence', '{ ...DEFAULT_POLICIES, ...this.meta.policies }', '{ ...this.meta.policies, ...DEFAULT_POLICIES }'],
		['spread default property', 'export const DEFAULT_POLICIES: RolePolicies = {', 'export const DEFAULT_POLICIES: RolePolicies = {\n ...other,'],
		['computed returned property', "gtlAvailable: calc('gtlAvailable',", "['gtlAvailable']: calc('gtlAvailable',"],
		['generator method', 'public async getUserPolicies(', 'public async *getUserPolicies('],
		['invalid syntax', 'vs => Math.max(...vs)', 'vs => {)'],
	])('fails closed on %s', (_name, before, after) => {
		expect(() => generatePolicyAggregation(replace(before, after))).toThrow('Unsupported RoleService policy source');
	});
});
