import { spawnSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = dirname(fileURLToPath(import.meta.url));
const licenseName = /^(licen[sc]e|copying|notice|copyright|authors)([._-]|$)/i;

function licenseFiles(directory) {
	return readdirSync(directory, { withFileTypes: true }).flatMap(entry => {
		const path = join(directory, entry.name);
		if (entry.isDirectory()) return licenseFiles(path);
		return entry.isFile() && licenseName.test(entry.name) ? [path] : [];
	}).sort();
}

export function renderNotices(metadata, policy, supplementsRoot, lockHash) {
	const sections = [
		'SLACC THIRD-PARTY NOTICES',
		'Generated by bun run --filter slacc licenses. Do not edit manually.',
		`Cargo.lock SHA-256: ${lockHash}`,
		'Includes the complete locked Cargo graph, including build tools and other platforms.',
		'License choices below apply to the SPDX expressions; original texts may include alternatives.',
		'Bundled native third-party notices are preserved as supplied by each crate.',
		'Slacc itself is MIT licensed; see the accompanying LICENSE.',
	];
	const packages = metadata.packages.filter(pkg => pkg.name !== 'slacc').sort((a, b) => {
		const left = `${a.name}@${a.version}`;
		const right = `${b.name}@${b.version}`;
		return left < right ? -1 : left > right ? 1 : 0;
	});
	for (const pkg of packages) {
		if (!Object.hasOwn(policy.licenses, pkg.license)) {
			throw new Error(`Unreviewed license: ${pkg.name}@${pkg.version}: ${pkg.license}`);
		}
		if (!pkg.source?.startsWith('registry+')) throw new Error(`Unreviewed source: ${pkg.name}`);
		const directory = dirname(pkg.manifest_path);
		const texts = licenseFiles(directory).map(path => ({
			label: relative(directory, path).split('\\').join('/'),
			text: readFileSync(path, 'utf8'),
		}));
		const supplement = policy.supplements[`${pkg.name}@${pkg.version}`];
		if (supplement) {
			if (supplement.license !== pkg.license) throw new Error(`Supplement license changed: ${pkg.name}`);
			for (const file of supplement.files) {
				texts.push({ label: file.source, text: readFileSync(join(supplementsRoot, file.path), 'utf8') });
			}
		}
		if (texts.length === 0) throw new Error(`No license text for ${pkg.name}@${pkg.version}`);
		sections.push(
			'='.repeat(80), `${pkg.name} ${pkg.version}`,
			`Source: https://crates.io/crates/${pkg.name}/${pkg.version}`,
			`Repository: ${pkg.repository ?? '(not specified)'}`,
			`Declared license: ${pkg.license}`, `Selected license: ${policy.licenses[pkg.license]}`,
		);
		for (const { label, text } of texts) {
			if (!text.trim() || text.includes('\0') || text.includes('\uFFFD')) {
				throw new Error(`Invalid license text: ${pkg.name}: ${label}`);
			}
			sections.push(`--- ${label}\n${text.replaceAll('\r\n', '\n').replace(/[ \t]+$/gm, '').trimEnd()}`);
		}
	}
	return sections.join('\n\n') + '\n';
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
	if (process.argv.slice(2).some(arg => arg !== '--check')) throw new Error('Usage: licenses.mjs [--check]');
	const result = spawnSync('cargo', ['metadata', '--locked', '--format-version', '1'], {
		cwd: root, encoding: 'utf8', stdio: ['ignore', 'pipe', 'inherit'], maxBuffer: 32 * 1024 * 1024,
	});
	if (result.error) throw result.error;
	if (result.status !== 0) process.exit(result.status ?? 1);
	const policy = JSON.parse(readFileSync(join(root, 'license-policy.json'), 'utf8'));
	const hash = createHash('sha256').update(readFileSync(join(root, 'Cargo.lock'))).digest('hex');
	const notices = renderNotices(JSON.parse(result.stdout), policy, root, hash);
	const output = join(root, 'THIRD-PARTY-NOTICES.txt');
	if (process.argv.includes('--check')) {
		if (readFileSync(output, 'utf8') !== notices) throw new Error('Notices are stale; run bun run --filter slacc licenses');
		console.log('slacc third-party notices: up to date');
	} else {
		writeFileSync(output, notices);
		console.log(`Wrote ${output}`);
	}
}
