import { createHash, randomBytes, randomUUID } from 'node:crypto';
import {
	copyFile,
	lstat,
	mkdir,
	readFile,
	realpath,
	rename,
	rm,
	writeFile,
} from 'node:fs/promises';
import { join } from 'node:path';
import { createInterface } from 'node:readline';
import { fileURLToPath } from 'node:url';

const rootDirectory = fileURLToPath(new URL('../..', import.meta.url));
const actions = ['setup', 'destroy', 'clean-cache', 'migrate', 'start'];
const ownerLabel = 'org.misskey.dev-docker.owner';
const environmentLabel = 'org.misskey.environment';
const projectLabel = 'com.docker.compose.project';

/** 空入力・EOF・中断を含め、明示的なy以外では変更しません。 */
export async function confirmDevelopmentAction(message, signal) {
	console.log(`${message}\nContinue? [y/N]`);
	if (signal?.aborted) return false;
	const reader = createInterface({ input: process.stdin, crlfDelay: Infinity });
	return new Promise((resolveAnswer) => {
		let answered = false;
		const finish = (answer) => {
			if (answered) return;
			answered = true;
			signal?.removeEventListener('abort', cancel);
			reader.close();
			resolveAnswer(answer);
		};
		const cancel = () => finish(false);
		reader.once('line', (line) => finish(line.trim().toLowerCase() === 'y'));
		reader.once('close', cancel);
		reader.once('SIGINT', cancel);
		signal?.addEventListener('abort', cancel, { once: true });
	});
}

async function safeDirectory(path) {
	try {
		const info = await lstat(path);
		if (info.isSymbolicLink() || !info.isDirectory()) throw new Error(`Unsafe directory or symlink: ${path}`);
	} catch (error) {
		if (error.code !== 'ENOENT') throw error;
	}
}

async function optionalFile(path) {
	try {
		const info = await lstat(path);
		if (info.isSymbolicLink() || !info.isFile()) throw new Error(`Unsafe file or symlink: ${path}`);
		return await readFile(path, 'utf8');
	} catch (error) {
		if (error.code === 'ENOENT') return null;
		throw error;
	}
}

async function writeAtomic(path, content) {
	const temporary = `${path}.${randomUUID()}.tmp`;
	try {
		await writeFile(temporary, content, { mode: 0o600, flag: 'wx' });
		await rename(temporary, path);
	} finally {
		await rm(temporary, { force: true });
	}
}

function developmentConfig(state) {
	return `# Generated by dev-docker:setup. Development only.
url: http://localhost:3000
port: 3000
db:
  host: 127.0.0.1
  port: 15432
  db: misskey_dev
  user: misskey_dev
  pass: ${state.password}
dbReplications: false
redis:
  host: 127.0.0.1
  port: 16379
id: aidx
fulltextSearch:
  provider: sqlLike
`;
}

function dockerEnvironment(state) {
	return `POSTGRES_USER=misskey_dev\nPOSTGRES_DB=misskey_dev\nPOSTGRES_PASSWORD=${state.password}\n`;
}

/** Dockerの実行境界と確認入力だけを差し替え、ファイル処理・所有権判定は実処理を使います。 */
export async function runDevDocker(action, options = {}) {
	if (!actions.includes(action)) throw new Error(`Unknown action. Use: ${actions.join(', ')}`);
	const env = options.env ?? process.env;
	if (env.NODE_ENV === 'production') throw new Error('Refusing dev-docker in NODE_ENV=production.');
	const root = await realpath(options.root ?? rootDirectory);
	const configRoot = join(root, '.config');
	const directory = join(configRoot, 'dev-docker');
	const log = options.log ?? console.log;
	const confirm = options.confirm ?? confirmDevelopmentAction;
	const project = `misskey-dev-${createHash('sha256').update(root).digest('hex').slice(0, 12)}`;
	const composeFile = join(root, 'scripts/dev/compose.yml');
	const stateFile = join(directory, 'state.json');
	const execute =
		options.execute ??
		(async (args, settings) => {
			const child = Bun.spawn(args, {
				cwd: settings.cwd,
				env: settings.env,
				stdin: 'inherit',
				stdout: settings.capture ? 'pipe' : 'inherit',
				stderr: 'inherit',
				signal: options.signal,
			});
			const output = settings.capture
				? new Response(child.stdout).text()
				: Promise.resolve('');
			const [code, stdout] = await Promise.all([child.exited, output]);
			if (code !== 0) throw new Error(`Command failed (${code}): ${args[0]} ${args[1]}`);
			return stdout.trim();
		});
	const command = (args, settings = {}) =>
		execute(args, { cwd: root, env, ...settings });
	const docker = (args) => command(['docker', ...args], { capture: true });

	const messages = {
		setup:
			'Generate development config in .config/dev-docker/, back up changed settings, start dedicated PostgreSQL/Redis containers, and build Misskey with Bun on the host.',
		destroy: `Remove containers and all PostgreSQL/Redis data for development environment ${project}. Stop Misskey on the host before continuing.`,
		'clean-cache':
			'Remove all unused build cache from the connected Docker daemon, including cache from other projects. Images and PostgreSQL/Redis data will be preserved.',
		migrate: 'Apply migrations to the dedicated development PostgreSQL database.',
		start:
			'Start Misskey with Bun on the host using the dedicated development config and storage.',
	};
	if (!(await confirm(`${messages[action]}\nTarget: ${root}`))) {
		log('Cancelled.');
		return;
	}
	if (action === 'clean-cache') {
		await command(['docker', 'info', '--format', '{{.ID}}'], { capture: true });
		await command(['docker', 'builder', 'prune', '--all', '--force']);
		return;
	}

	await safeDirectory(configRoot);
	await safeDirectory(directory);
	const rawState = await optionalFile(stateFile);
	let state;
	if (rawState !== null) {
		try {
			state = JSON.parse(rawState);
		} catch {
			throw new Error('Invalid development ownership state.');
		}
		if (
			state.version !== 1 ||
			state.root !== root ||
			state.project !== project ||
			!/^[a-f0-9]{32}$/.test(state.owner) ||
			!/^[a-f0-9]{64}$/.test(state.password) ||
			typeof state.daemonId !== 'string' ||
			state.daemonId.length === 0
		) {
			throw new Error('Invalid or copied development ownership state.');
		}
	} else if (action !== 'setup') {
		throw new Error(
			'Development ownership state is missing. Run dev-docker:setup in this checkout first.',
		);
	}

	await mkdir(directory, { recursive: true, mode: 0o700 });
	// setup・destroy・ネイティブ起動を同じcheckoutで同時実行しません。
	const lock = join(directory, 'operation.lock');
	try {
		await mkdir(lock);
	} catch (error) {
		if (error.code === 'EEXIST') {
			throw new Error(
				'Another development operation is running (operation.lock).',
			);
		}
		throw error;
	}
	try {
		const endpoint = env.DOCKER_HOST && !env.DOCKER_CONTEXT
			? env.DOCKER_HOST
			: await docker(['context', 'inspect', ...(env.DOCKER_CONTEXT ? [env.DOCKER_CONTEXT] : []), '--format', '{{.Endpoints.docker.Host}}']);
		if (!endpoint.startsWith('unix://') && !endpoint.startsWith('npipe://')) {
			throw new Error('A local Docker Unix socket or named pipe is required; remote Docker endpoints are unsupported.');
		}
		const daemonId = (await docker(['info', '--format', '{{.ID}}'])).trim();
		if (!daemonId) throw new Error('Cannot identify Docker daemon.');
		if (state && state.daemonId !== daemonId) {
			throw new Error(
				'Docker daemon differs from the development ownership state.',
			);
		}
		state ??= {
			version: 1,
			root,
			project,
			daemonId,
			owner: randomBytes(16).toString('hex'),
			password: randomBytes(32).toString('hex'),
		};

		const inspect = async (type, listing) => {
			const ids = (await docker(listing)).split(/\s+/).filter(Boolean);
			if (ids.length === 0) return [];
			const items = JSON.parse(await docker([type, 'inspect', ...ids]));
			if (!Array.isArray(items) || items.length !== ids.length) throw new Error('Incomplete Docker ownership inspection.');
			return items;
		};
		const containers = await inspect('container', [
			'container',
			'ls',
			'--all',
			'--quiet',
			'--filter',
			`label=${projectLabel}=${project}`,
		]);
		const volumes = await inspect('volume', [
			'volume',
			'ls',
			'--quiet',
			'--filter',
			`name=${project}_`,
		]);
		const networks = await inspect('network', [
			'network',
			'ls',
			'--quiet',
			'--filter',
			`name=${project}_default`,
		]);
		const volumeNames = new Set([`${project}_postgres`, `${project}_redis`]);
		for (const [type, items] of [
			['container', containers],
			['volume', volumes],
			['network', networks],
		]) {
			for (const item of items) {
				const labels = type === 'container' ? item.Config?.Labels : item.Labels;
				if (
					labels?.[ownerLabel] !== state.owner ||
					labels?.[environmentLabel] !== 'development' ||
					labels?.[projectLabel] !== project
				) {
					throw new Error(
						`Docker ${type} ownership does not match this development environment.`,
					);
				}
				if (type === 'volume' && !volumeNames.has(item.Name)) throw new Error('Unexpected development volume ownership.');
				if (type === 'network' && item.Name !== `${project}_default`) throw new Error('Unexpected development network ownership.');
				if (type === 'container') {
					const service = labels['com.docker.compose.service'];
					if (
						!['db', 'redis'].includes(service) ||
						item.Name !== `/${project}-${service}-1`
					) {
						throw new Error('Unexpected container ownership.');
					}
					const expectedVolume = `${project}_${service === 'db' ? 'postgres' : 'redis'}`;
					if (
						!Array.isArray(item.Mounts) ||
						item.Mounts.length !== 1 ||
						item.Mounts[0].Type !== 'volume' ||
						item.Mounts[0].Name !== expectedVolume
					) {
						throw new Error(
							'Unexpected container mount; refusing to touch production or bind-mounted data.',
						);
					}
				}
			}
		}

		if (action === 'destroy') {
			// Compose設定・本番のbind mount・共有pruneを経由せず、検査済みのIDとvolume名だけを削除します。
			if (containers.length) {
				await command([
					'docker',
					'container',
					'rm',
					'--force',
					...containers.map((item) => item.Id),
				]);
			}
			if (networks.length) {
				await command([
					'docker',
					'network',
					'rm',
					...networks.map((item) => item.Id),
				]);
			}
			if (volumes.length) {
				await command([
					'docker',
					'volume',
					'rm',
					...volumes.map((item) => item.Name),
				]);
			}
			log(
				'Removed development containers and PostgreSQL/Redis data. Config, backups, and uploaded files have been preserved.',
			);
			return;
		}

		const nativeEnv = {
			...env,
			NODE_ENV: 'development',
			MISSKEY_CONFIG_YML: 'dev-docker/default.yml',
			MISSKEY_CONFIG_JSON: join(directory, 'compiled.json'),
			MISSKEY_FILES_DIR: join(directory, 'storage/files'),
		};
		delete nativeEnv.MISSKEY_STORAGE_ROOT;
		await safeDirectory(join(directory, 'storage'));
		await safeDirectory(join(directory, 'storage/files'));
		await optionalFile(join(directory, 'compiled.json'));
		if (action === 'migrate' || action === 'start') {
			for (const [service, containerPort, hostPort] of [['db', '5432/tcp', '15432'], ['redis', '6379/tcp', '16379']]) {
				const container = containers.find((item) => item.Config.Labels['com.docker.compose.service'] === service);
				const bindings = container?.HostConfig?.PortBindings?.[containerPort];
				if (!container?.State?.Running || bindings?.length !== 1 || bindings[0].HostIp !== '127.0.0.1' || bindings[0].HostPort !== hostPort) {
					throw new Error('Expected running development containers on the dedicated localhost ports. Run dev-docker:setup first.');
				}
			}
			if (
				(await optionalFile(join(directory, 'default.yml'))) !==
				developmentConfig(state)
			) {
				throw new Error(
					'Development config differs from generated settings. Run dev-docker:setup again.',
				);
			}
			await command([process.execPath, 'run', action], { env: nativeEnv });
			return;
		}

		const files = {
			'default.yml': developmentConfig(state),
			'docker.env': dockerEnvironment(state),
		};
		const changed = [];
		for (const [name, content] of Object.entries(files)) {
			const previous = await optionalFile(join(directory, name));
			if (previous !== null && previous !== content) changed.push(name);
		}
		if (changed.length) {
			const backups = join(directory, 'backups');
			await safeDirectory(backups);
			const backup = join(
				backups,
				`${new Date().toISOString().replace(/[:.]/g, '-')}-${randomUUID()}`,
			);
			await mkdir(backup, { recursive: true, mode: 0o700 });
			for (const name of changed) await copyFile(join(directory, name), join(backup, name));
			log(`Backed up development config: ${backup}`);
		}
		await writeAtomic(stateFile, JSON.stringify(state, null, 2) + '\n');
		for (const [name, content] of Object.entries(files)) await writeAtomic(join(directory, name), content);
		const composeEnv = {
			...env,
			MISSKEY_DEV_DOCKER_OWNER: state.owner,
			MISSKEY_DEV_DOCKER_ENV: join(directory, 'docker.env'),
		};
		const compose = [
			'docker',
			'compose',
			'--project-name',
			project,
			'--file',
			composeFile,
			'--env-file',
			join(directory, 'docker.env'),
		];
		await command([...compose, 'pull', 'db', 'redis'], { env: composeEnv });
		await command(
			[
				...compose,
				'up',
				'--detach',
				'--wait',
				'--wait-timeout',
				'120',
				'db',
				'redis',
			],
			{ env: composeEnv },
		);
		await command([process.execPath, 'install', '--frozen-lockfile'], {
			env: nativeEnv,
		});
		// Viteの開発サーバー用設定はdefault.ymlを参照するため、配信用アセットをproductionモードでビルドします。
		await command([process.execPath, 'run', 'build'], { env: { ...nativeEnv, NODE_ENV: 'production' } });
		log(
			'Setup complete. Run these commands in order:\n  bun run dev-docker:migrate\n  bun run dev-docker:start\nURL: http://localhost:3000',
		);
	} finally {
		await rm(lock, { recursive: true, force: true });
	}
}

if (import.meta.main) {
	const [action, ...extra] = process.argv.slice(2);
	if (action === '--help' && extra.length === 0) {
		console.log(
			`bun scripts/dev/docker.mjs <${actions.join('|')}>\nEvery action requires y/N confirmation before it runs.`,
		);
	} else {
		const abort = new AbortController();
		const stop = () => abort.abort();
		process.once('SIGINT', stop);
		process.once('SIGTERM', stop);
		try {
			if (extra.length) throw new Error('Unexpected arguments. Use --help.');
			await runDevDocker(action, {
				signal: abort.signal,
				confirm: (message) => confirmDevelopmentAction(message, abort.signal),
			});
		} catch (error) {
			console.error(error.message);
			process.exitCode = 1;
		} finally {
			process.off('SIGINT', stop);
			process.off('SIGTERM', stop);
		}
	}
}
